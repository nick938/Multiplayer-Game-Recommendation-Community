/**
 * Embeds drizzle-kit generated migration SQL into a TS module so the runtime
 * migrator never touches the filesystem (bundlers like Turbopack rewrite the
 * path lookups drizzle's file-based migrator depends on).
 *
 * Run after `pnpm db:generate`:
 *   pnpm --filter @mgc/db embed
 */
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const drizzleDir = path.resolve(here, '..', 'drizzle')
const outFile = path.resolve(here, '..', 'src', 'migrations.generated.ts')

const journal = JSON.parse(fs.readFileSync(path.join(drizzleDir, 'meta', '_journal.json'), 'utf8'))
const entries = journal.entries ?? []

const lines = [
  '// GENERATED by scripts/embed-migrations.mjs — do not edit.',
  '// Source of truth: drizzle/*.sql (drizzle-kit generate).',
  'export interface EmbeddedMigration {',
  '  tag: string',
  '  statements: string[]',
  '}',
  '',
  'export const EMBEDDED_MIGRATIONS: EmbeddedMigration[] = [',
]

for (const entry of entries) {
  // Journal tags omit the .sql extension (drizzle-kit convention).
  const file = path.join(drizzleDir, `${entry.tag}.sql`)
  const statements = fs
    .readFileSync(file, 'utf8')
    .split('--> statement-breakpoint')
    .map((statement) => statement.trim())
    .filter((statement) => statement.length > 0)
  lines.push('  {')
  lines.push(`    tag: ${JSON.stringify(entry.tag)},`)
  lines.push('    statements: [')
  for (const statement of statements) {
    lines.push(`      ${JSON.stringify(statement)},`)
  }
  lines.push('    ],')
  lines.push('  },')
}
lines.push(']', '')

const banner = `// embedded at ${new Date().toISOString()} · sha256 ${crypto.createHash('sha256').update(lines.join('\n')).digest('hex').slice(0, 12)}\n`
fs.writeFileSync(outFile, banner + lines.join('\n'))
console.log(`embedded ${entries.length} migrations -> ${path.relative(process.cwd(), outFile)}`)
